def mix_with(state, matrix):
    out = [0] * 16
    for col in range(4):
        column = state[col * 4:col * 4 + 4]
        for row in range(4):
            value = 0
            for k in range(4):
                value ^= gmul(matrix[row][k], column[k])
            out[col * 4 + row] = value
    return out


def mix_columns(state):
    return mix_with(state, MIX_MATRIX)


def inv_mix_columns(state):
    return mix_with(state, INV_MIX_MATRIX)


def encrypt_block(block, key):
    if len(block) != BLOCK_SIZE:
        raise ValueError("block must be 16 bytes")
    round_keys = expand_key(key)
    state = add_round_key(list(block), round_keys[0])
    for r in range(1, ROUNDS):
        state = sub_bytes(state)
        state = shift_rows(state)
        state = mix_columns(state)
        state = add_round_key(state, round_keys[r])
    state = sub_bytes(state)
    state = shift_rows(state)
    state = add_round_key(state, round_keys[ROUNDS])
    return bytes(state)


def decrypt_block(block, key):
    if len(block) != BLOCK_SIZE:
        raise ValueError("block must be 16 bytes")
    round_keys = expand_key(key)
    state = add_round_key(list(block), round_keys[ROUNDS])
    for r in range(ROUNDS - 1, 0, -1):
        state = inv_shift_rows(state)
        state = inv_sub_bytes(state)
        state = add_round_key(state, round_keys[r])
        state = inv_mix_columns(state)
    state = inv_shift_rows(state)
    state = inv_sub_bytes(state)
    state = add_round_key(state, round_keys[0])
    return bytes(state)


ALPHABET = string.ascii_letters + string.digits


def random_bytes(n):
    return secrets.token_bytes(n)


def random_ascii(n):
    return "".join(secrets.choice(ALPHABET) for _ in range(n)).encode("ascii")


def new_nonce():
    return str(secrets.randbelow(2 ** 32))


MODE_ECB = 0
MODE_CBC = 1


def pad(data):
    count = BLOCK_SIZE - len(data) % BLOCK_SIZE
    return data + bytes([count]) * count


def unpad(data):
    if not data or len(data) % BLOCK_SIZE:
        raise ValueError("invalid data length")
    count = data[-1]
    if count < 1 or count > BLOCK_SIZE or data[-count:] != bytes([count]) * count:
        raise ValueError("bad padding, wrong key?")
    return data[:-count]


def xor_bytes(a, b):
    return bytes(x ^ y for x, y in zip(a, b))


def split_blocks(data):
    return [data[i:i + BLOCK_SIZE] for i in range(0, len(data), BLOCK_SIZE)]


def ecb_encrypt(plaintext, key):
    return b"".join(encrypt_block(b, key) for b in split_blocks(pad(plaintext)))


def ecb_decrypt(ciphertext, key):
    if len(ciphertext) % BLOCK_SIZE:
        raise ValueError("ciphertext length must be a multiple of 16")
    plain = b"".join(decrypt_block(b, key) for b in split_blocks(ciphertext))
    return unpad(plain)


def cbc_encrypt(plaintext, key, iv):
    previous = iv
    out = []
    for block in split_blocks(pad(plaintext)):
        previous = encrypt_block(xor_bytes(block, previous), key)
        out.append(previous)
    return b"".join(out)


def cbc_decrypt(ciphertext, key, iv):
    if len(ciphertext) % BLOCK_SIZE:
        raise ValueError("ciphertext length must be a multiple of 16")
    previous = iv
    out = []
    for block in split_blocks(ciphertext):
        out.append(xor_bytes(decrypt_block(block, key), previous))
        previous = block
    return unpad(b"".join(out))


def seal(plaintext, key, mode):
    if mode == MODE_ECB:
        return bytes([MODE_ECB]) + ecb_encrypt(plaintext, key)
    if mode == MODE_CBC:
        iv = random_bytes(BLOCK_SIZE)
        return bytes([MODE_CBC]) + encrypt_block(iv, key) + cbc_encrypt(plaintext, key, iv)
    raise ValueError("unknown mode")


def unseal(message, key):
    if len(message) < 1:
        raise ValueError("empty message")
    mode, body = message[0], message[1:]
    if mode == MODE_ECB:
        return ecb_decrypt(body, key)
    if mode == MODE_CBC:
        iv = decrypt_block(body[:BLOCK_SIZE], key)
        return cbc_decrypt(body[BLOCK_SIZE:], key, iv)
    raise ValueError("unknown mode")


KEY_SIZE = 16


def validate_key(text):
    if len(text) != KEY_SIZE:
        raise ValueError(f"key must be exactly {KEY_SIZE} characters")
    if any(ord(c) < 32 or ord(c) > 126 for c in text):
        raise ValueError("key must be printable ASCII")
    return text.encode("ascii")


def validate_id(text):
    if not text or not text.isascii() or not text.isalnum():
        raise ValueError("ID must be ASCII letters and digits only")
    return text


def ask_key(label):
    while True:
        text = input(f"Enter {label} (ASCII, {KEY_SIZE} characters): ")
        try:
            validate_key(text)
        except ValueError as error:
            print(error)
            continue
        return text


def send_line(sock, text):
    sock.sendall((text + "\n").encode("ascii"))


def recv_line(reader):
    line = reader.readline()
    if not line:
        raise ConnectionError("connection closed")
    return line.rstrip("\n")